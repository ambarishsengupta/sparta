#!/usr/bin/env bash
# gen-types (WO-0126, audit finding A6): writes the TypeScript types of the database to apps/web/lib/supabase/database.types.ts,
# read from the LOCAL Supabase stack (`supabase gen types typescript --local`; nothing here can reach a linked or hosted project) for
# the schemas app, catalog, ops and analytics. Run it after every migration, with the stack up and the database reset to the committed
# migrations (`supabase db reset`), and commit the result. The gate's types_drift check (workflow/gates/types_drift.sh) regenerates the
# types to a temporary file and fails when they differ from the committed one.
#
#   bash supabase/scripts/gen-types.sh [OUTPUT_FILE]      # default OUTPUT_FILE: apps/web/lib/supabase/database.types.ts
#
# Deterministic: the same schema gives a byte-identical file. The file holds no secret, no path and no date. It is written only when the
# generator exits 0 and its output holds the Database type (the target is never left half-written, also not after a time-out or a crash), through a
# temporary file next to it. Hard time limit: 120 seconds.
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../.." || exit 2
out="${1:-apps/web/lib/supabase/database.types.ts}"
SCHEMAS="app,catalog,ops,analytics"

if ! command -v supabase >/dev/null 2>&1; then echo "gen-types: the supabase CLI is not installed." >&2; exit 2; fi
if ! supabase status >/dev/null 2>&1; then echo "gen-types: the local Supabase stack is not running (start it with 'supabase start')." >&2; exit 2; fi

tmp="$(mktemp "${out}.XXXXXX")" || { echo "gen-types: cannot write next to ${out}." >&2; exit 2; }
trap 'rm -f "$tmp"' EXIT
{
  echo "// GENERATED by supabase/scripts/gen-types.sh from the local database (schemas: ${SCHEMAS}). Do not edit by hand."
  echo "// After a migration: supabase db reset && bash supabase/scripts/gen-types.sh, then commit this file."
  if command -v timeout >/dev/null 2>&1; then timeout -k 10 120 supabase gen types typescript --local --schema "$SCHEMAS" 2>/dev/null </dev/null
  else perl -e 'alarm shift; exec @ARGV' 120 supabase gen types typescript --local --schema "$SCHEMAS" 2>/dev/null </dev/null; fi
} > "$tmp" || { echo "gen-types: the generator failed; ${out} was not changed." >&2; exit 1; }   # the group's status is the generator's: a time-out (124) or a crash is a failure
# A generator that exits 0 must also have printed the types.
if ! grep -q '^export type Database = {' "$tmp"; then echo "gen-types: the generator did not produce the Database type; ${out} was not changed." >&2; exit 1; fi
mv "$tmp" "$out" && chmod 644 "$out" && trap - EXIT
echo "gen-types: wrote ${out} ($(wc -l < "$out" | tr -d ' ') lines)"
