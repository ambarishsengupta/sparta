// Generates supabase/seed/lookups.sql from packages/taxonomy/src/taxonomy.json (WO-0040, CC5).
// Run: npm run db:seed (tsx supabase/scripts/gen-seed.ts). The committed file must equal a fresh generation.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface Taxonomy {
  categories: { name: string; subTypes: string[] }[];
  colourFamilies: { family: string; swatches: string[] }[];
  fit: string[];
  material: string[];
  pattern: string[];
  seasons: string[];
  occasions: string[];
  conditionBands: { code: string; min: number; max: number }[];
  sizeSystems: { code: string; label: string }[];
}

const TAXONOMY_URL = new URL('../../packages/taxonomy/src/taxonomy.json', import.meta.url);
export const SEED_URL = new URL('../seed/lookups.sql', import.meta.url);

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const upsert = (conflict: string, cols: string[]): string =>
  `on conflict (${conflict}) do update set ${cols.map((c) => `${c} = excluded.${c}`).join(', ')};`;

// code = label = the taxonomy name, sort = position in the taxonomy list (1-based), all active
function simple(table: string, rows: { code: string; label?: string }[]): string {
  const values = rows.map((r, i) => `(${q(r.code)}, ${q(r.label ?? r.code)}, ${i + 1}, true)`);
  return `insert into catalog.${table} (code, label, sort, active) values\n  ${values.join(',\n  ')}\n${upsert('code', ['label', 'sort', 'active'])}\n`;
}

export function generateLookupsSql(taxonomy: Taxonomy = JSON.parse(readFileSync(TAXONOMY_URL, 'utf8')) as Taxonomy): string {
  const t = taxonomy;
  const names = (a: string[]) => a.map((code) => ({ code }));
  const out: string[] = [
    '-- GENERATED by supabase/scripts/gen-seed.ts from packages/taxonomy/src/taxonomy.json. Do not edit by hand.',
    '-- Idempotent: every statement is an upsert. Regenerate with `npm run db:seed`.\n',
    simple('lk_category', t.categories.map((c) => ({ code: c.name }))),
  ];
  const subTypes = t.categories.flatMap((c) =>
    c.subTypes.map((s, i) => `(${q(c.name)}, ${q(s)}, ${q(s)}, ${i + 1}, true)`));
  out.push(`insert into catalog.lk_sub_type (category, code, label, sort, active) values\n  ${subTypes.join(',\n  ')}\n${upsert('category, code', ['label', 'sort', 'active'])}\n`);
  out.push(simple('lk_colour_family', names(t.colourFamilies.map((c) => c.family))));
  out.push(simple('lk_fit', names(t.fit)), simple('lk_material', names(t.material)), simple('lk_pattern', names(t.pattern)));
  out.push(simple('lk_season', names(t.seasons)), simple('lk_occasion', names(t.occasions)), simple('lk_size_system', t.sizeSystems));
  const bands = t.conditionBands.map((b, i) => `(${q(b.code)}, ${q(b.code)}, ${i + 1}, true, ${b.min}, ${b.max})`);
  out.push(`insert into catalog.lk_condition_band (code, label, sort, active, min_score, max_score) values\n  ${bands.join(',\n  ')}\n${upsert('code', ['label', 'sort', 'active', 'min_score', 'max_score'])}\n`);
  // Swatches in seed order; id = position, so the colour function's tie-break (lowest id) is the first listed swatch.
  const swatches = t.colourFamilies.flatMap((c) => c.swatches.map((hex) => ({ family: c.family, hex })))
    .map((s, i) => {
      const n = parseInt(s.hex.slice(1), 16);
      return `(${i + 1}, ${q(s.family)}, ${q(s.hex)}, ${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255})`;
    });
  out.push(`-- CIELAB values are computed by the database from the sRGB value (LLD 4.3: "filled by the seed")`,
    `insert into catalog.colour_family_ref (id, family, hex, l, a, b)\nselect v.id, v.family, v.hex, x.lab[1], x.lab[2], x.lab[3]\nfrom (values\n  ${swatches.join(',\n  ')}\n) as v(id, family, hex, r, g, b),\n  lateral (select catalog.rgb_to_lab(v.r, v.g, v.b) as lab) x\n${upsert('id', ['family', 'hex', 'l', 'a', 'b'])}`,
    `select setval(pg_get_serial_sequence('catalog.colour_family_ref', 'id'), (select max(id) from catalog.colour_family_ref));\n`);
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(SEED_URL, generateLookupsSql());
  console.log(`wrote ${fileURLToPath(SEED_URL)}`);
}
