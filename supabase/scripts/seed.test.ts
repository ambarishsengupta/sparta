// CC5: the seed is generated, not hand-typed. Pure test (no database). Collected through workflow/gates/db_tests.test.ts,
// because vitest.config.ts only includes workflow/gates/**, packages/*/src/** and apps/web/**.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import taxonomy from '../../packages/taxonomy/src/taxonomy.json';
import { SEED_URL, generateLookupsSql } from './gen-seed';

describe('supabase/seed/lookups.sql is generated from the taxonomy', () => {
  it('the committed file equals a fresh generation (run `npm run db:seed` if this fails)', () => {
    expect(readFileSync(SEED_URL, 'utf8')).toBe(generateLookupsSql());
  });

  it('generation is deterministic', () => {
    expect(generateLookupsSql()).toBe(generateLookupsSql());
  });

  it('a change in the taxonomy changes the output (the generator really reads it)', () => {
    const changed = structuredClone(taxonomy);
    changed.categories[0]?.subTypes.push('Poncho');
    changed.colourFamilies[0]?.swatches.push('#010101');
    const sql = generateLookupsSql(changed);
    expect(sql).not.toBe(generateLookupsSql());
    expect(sql).toContain("('Tops', 'Poncho', 'Poncho', 7, true)");
    expect(sql).toContain("'Black', '#010101', 1, 1, 1");
  });

  it('every statement is an idempotent upsert and the file says it is generated', () => {
    const sql = generateLookupsSql();
    expect(sql.split('\n')[0]).toMatch(/^-- GENERATED by supabase\/scripts\/gen-seed\.ts/);
    const inserts = sql.match(/^insert into /gm)?.length ?? 0;
    expect(inserts).toBe(15);
    expect(sql.match(/^on conflict \(/gm)?.length).toBe(inserts);
  });

  it('quotes are escaped', () => {
    const t = structuredClone(taxonomy);
    t.fit.push("Men's");
    expect(generateLookupsSql(t)).toContain("'Men''s'");
  });
});

describe('WO-0098: the insight lookups come from the taxonomy (CC2)', () => {
  const sql = generateLookupsSql();
  it('the six price bands, the region map and the Letter sizes are in the generated file', () => {
    for (const code of ['<25', '25-50', '50-100', '100-200', '200+', 'Unknown']) expect(sql).toContain(`('${code}', '${code}', `);
    expect(sql).toContain("insert into catalog.lk_region (code, label, sort, active) values\n  ('South Asia', 'South Asia', 1, true)");
    expect(sql).toContain("insert into catalog.country_region (country, region) values\n  ('IN', 'South Asia')");
    expect(sql).toContain("('Letter', 'XXXL', 'XXXL', 7, true)");
  });
  it('lk_brand is never seeded (the brand list is the owner\'s, O3)', () => {
    expect(sql).not.toContain('lk_brand');
  });
  it('a change in the new taxonomy keys changes the output', () => {
    const changed = structuredClone(taxonomy);
    changed.priceBands.push('500+');
    changed.countryRegions.push({ country: 'LK', region: 'South Asia' });
    changed.sizes[0]?.codes.push('4XL');
    expect(generateLookupsSql(changed)).toContain("('LK', 'South Asia')");
    expect(generateLookupsSql(changed)).toContain("('Letter', '4XL', '4XL', 8, true)");
    expect(generateLookupsSql(changed)).toContain("('500+', '500+', 7, true)");
  });
});
